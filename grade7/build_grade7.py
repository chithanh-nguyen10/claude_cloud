#!/usr/bin/env python3
r"""
Build the Grade 7 ThinkAlgo worksheet set (4 topics x 4 editions = 16 files).

Sources
  preamble.tex            shared look (taken from the ThinkAlgo reference worksheet)
  labels_vi.tex/en.tex    language-dependent words (Bài/Problem, Lời giải/Solution, ...)
  body/<n>_<lang>_<part>.tex
                          content of topic n, part a (theory, examples, problems 1-15),
                          b (16-30), c (31-40), d (41-50)

Outputs (standalone, each compiles on its own with pdflatex)
  tex/<n>_<slug>_{HS,GV}_VI.tex   and   tex/<n>_<slug>_{Student,Teacher}_EN.tex
  pdf/  the compiled PDFs (with --pdf)

  python3 build_grade7.py            # assemble the .tex files only
  python3 build_grade7.py --pdf      # assemble and compile (two pdflatex passes)
  python3 build_grade7.py --pdf 2    # only topic 2
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))

TOPICS = {
    1: {"vi": ("Dai_so_va_Phuong_trinh", "Đại số và Phương trình"),
        "en": ("Algebra_and_Equations", "Algebra and Equations")},
    2: {"vi": ("Hinh_hoc_va_Do_luong", "Hình học và Đo lường"),
        "en": ("Geometry_and_Measurement", "Geometry and Measurement")},
    3: {"vi": ("To_hop_va_Xac_suat", "Đếm và Xác suất"),
        "en": ("Counting_and_Probability", "Counting and Probability")},
    4: {"vi": ("So_hoc_va_Tu_duy_so", "Số học và Tư duy số"),
        "en": ("Number_Sense", "Number Sense")},
}
EDITIONS = {"vi": (("HS", False), ("GV", True)),
            "en": (("Student", False), ("Teacher", True))}
PARTS = "abcd"


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf8") as fh:
        return fh.read()


def assemble(n, lang, teacher):
    slug, title = TOPICS[n][lang]
    pre = read("preamble.tex").split("\n", 1)
    body = []
    for p in PARTS:
        f = "body/%d_%s_%s.tex" % (n, lang, p)
        if os.path.exists(os.path.join(ROOT, f)):
            body.append("%% ---------------- part %s ----------------\n%s" % (p, read(f)))
        else:
            body.append("%% (part %s not written yet)\n" % p)
    return "\n".join([
        "%% ThinkAlgo — %s — %s" % (title, "Lớp 7" if lang == "vi" else "Grade 7"),
        "%% Edition: %s, %s.  Generated by build_grade7.py — edit body/ and rebuild."
        % ("teacher (with solutions)" if teacher else "student (no solutions)", lang.upper()),
        pre[0],
        r"\newif\ifsol \sol%s" % ("true" if teacher else "false"),
        pre[1],
        read("labels_%s.tex" % lang),
        r"\def\DocTopic{%s}" % title,
        r"\begin{document}",
        r"\titlehead",
        r"\chapterhead{%d}{%s}" % (n, title),
        "",
        "\n".join(body),
        r"\end{document}",
        "",
    ])


def compile_pdf(texdir, name):
    cmd = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", name + ".tex"]
    for _ in range(2):
        res = subprocess.run(cmd, cwd=texdir, capture_output=True, text=True,
                             encoding="utf8", errors="replace")
        if res.returncode != 0:
            sys.stderr.write(res.stdout[-4000:])
            raise SystemExit("ERROR: %s failed to compile" % name)
    log = open(os.path.join(texdir, name + ".log"), encoding="utf8", errors="replace").read()
    pages = [l for l in log.splitlines() if l.startswith("Output written")]
    over = log.count("Overfull \\hbox")
    print("  %-48s %s  (overfull hbox: %d)" % (name, pages[-1].split("(")[-1] if pages else "?", over))


def main():
    args = sys.argv[1:]
    want_pdf = "--pdf" in args
    only = [int(a) for a in args if a.isdigit()] or list(TOPICS)
    # G7_TEXDIR=/some/dir : private build folder (lets several people compile at once);
    # the PDFs then stay in that folder instead of being copied to pdf/
    texdir = os.environ.get("G7_TEXDIR") or os.path.join(ROOT, "tex")
    pdfdir = texdir if os.environ.get("G7_TEXDIR") else os.path.join(ROOT, "pdf")
    os.makedirs(texdir, exist_ok=True)
    if os.path.exists(os.path.join(ROOT, "logo.png")):
        shutil.copy(os.path.join(ROOT, "logo.png"), texdir)
    for n in only:
        for lang in ("vi", "en"):
            for tag, teacher in EDITIONS[lang]:
                name = "%d_%s_%s_%s" % (n, TOPICS[n][lang][0], tag, lang.upper())
                with open(os.path.join(texdir, name + ".tex"), "w", encoding="utf8") as fh:
                    fh.write(assemble(n, lang, teacher))
                if want_pdf:
                    compile_pdf(texdir, name)
                    os.makedirs(pdfdir, exist_ok=True)
                    if pdfdir != texdir:
                        shutil.copy(os.path.join(texdir, name + ".pdf"), pdfdir)
                    for ext in (("aux", "log", "out", "toc") if pdfdir == texdir else ("aux", "log", "out", "pdf", "toc")):
                        f = os.path.join(texdir, name + "." + ext)
                        if os.path.exists(f):
                            os.remove(f)
                else:
                    print("  wrote tex/%s.tex" % name)


if __name__ == "__main__":
    main()

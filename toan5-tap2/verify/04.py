def chk(label, got, exp):
    global ok
    got, exp = F(got), F(exp)
    good = got == exp
    ok &= good
    print("%-10s %-14s %-14s %s" % (label, got, exp, "OK" if good else "MISMATCH"))


def d(x):
    return F(x)


def vol(a, b, c):
    return d(a) * d(b) * d(c)


